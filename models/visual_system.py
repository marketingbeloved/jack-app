"""Визуальная система бренда для ТЗ на графику — и проверка, что ТЗ ей следует.

Зачем. Вика жаловалась: ТЗ на карусели приходят без стиля — подряд идут одинаковые
слайды, плашки прыгают с места на место, цвета повторяются и берутся наугад. Причина
была в коде: на весь графический ТЗ существовала одна строка «Бренд-стиль: cream
#FAF8F3 / sage-green #4A6B3A», и всё. Ни сетки, ни ролей слайдов, ни позиции плашки,
ни лимита текста — Джеку неоткуда было это взять.

Здесь собрана система из реальных фактов бренда: круглый navy-логотип, цветовое
кодирование упаковок по категориям (red Flea & Tick, blue Supplements, orange Yeast,
green Probiotic), тёплая земляная база и запрет на скруглённые «весёлые» шрифты
(это вайб Zesty Paws, от которого мы отстраиваемся).
"""

from __future__ import annotations

import re

# Категорийный акцент берётся от упаковки товара — он и так стоит на полке.
CATEGORY_ACCENT = {
    "flea": "#C0392B  (red — Flea & Tick)",
    "tick": "#C0392B  (red — Flea & Tick)",
    "supplement": "#2E5A8C  (blue — Supplements)",
    "yeast": "#D97C2B  (orange — Yeast Support)",
    "probiotic": "#3E7A4E  (green — Probiotic)",
    "eye": "#2E5A8C  (blue — Eye & Ear care)",
    "ear": "#2E5A8C  (blue — Eye & Ear care)",
    "calming": "#6B4E8C  (plum — Calming)",
    "treat": "#A86B4A  (clay — Treats)",
}
BASE_PAPER = "#FAF8F3"
INK = "#2B2A28"


def accent_for(text: str) -> str:
    """Акцентный цвет по товару/теме — из цветового кодирования упаковок."""
    low = (text or "").lower()
    for key, color in CATEGORY_ACCENT.items():
        if key in low:
            return color
    return "#2E5A8C  (blue — базовый, если категория не определяется)"


def visual_block(product_or_theme: str = "") -> str:
    """Визуальная система для промпта ТЗ на графику."""
    accent = accent_for(product_or_theme)
    return f"""
=== ВИЗУАЛЬНАЯ СИСТЕМА BELOVED PETS (обязательна для графики) ===

ХОЛСТ И СЕТКА
- Карусель/пост в ленту: 1080 × 1350 (4:5). Сторис: 1080 × 1920.
- Безопасные поля 80 px со всех сторон. Нижние 120 px не занимать — их режет интерфейс.
- Один смысловой блок на слайд. Пустое место — часть дизайна, не «дырка».

ЦВЕТ — самое частое нарушение
- База всегда спокойная: paper {BASE_PAPER} или тёплый clay/cream. Текст — ink {INK}.
- АКЦЕНТ НА ВСЮ КАРУСЕЛЬ РОВНО ОДИН, по категории товара. Для этой темы: {accent}
- Цвет акцента = цвет упаковки этой категории (red Flea & Tick, blue Supplements,
  orange Yeast, green Probiotic, plum Calming, clay Treats). Не выдумывать свой.
- ЗАПРЕЩЕНО: два категорийных цвета в одной карусели; менять акцент от слайда к слайду;
  градиенты на тексте; кислотные и неоновые оттенки.

ТИПОГРАФИКА
- Одна пара шрифтов на весь набор: тонкий serif для заголовков + нейтральный sans для
  подписей. НИКАКИХ скруглённых «весёлых» шрифтов — это вайб Zesty Paws.
- Шкала при 1080×1350: заголовок 72-84 px, подзаголовок 40-44 px, подпись/дисклеймер 28 px.
- Заголовок ≤ 6 слов. Подстрочник ≤ 12 слов. Больше — не влезет и не прочитается.
- Никаких предложений подряд сплошным текстом: слайд читается за 1,5 секунды.

ПЛАШКИ И ПОДПИСИ
- Позиция плашки задаётся явно И ОДИНАКОВА во всех слайдах набора (по умолчанию —
  нижняя треть, левый край по сетке, отступ 80 px). Плашка не должна «прыгать».
- Скругление 8 px, заливка — акцент на 90 % либо paper на 85 %. Обводок нет.
- На слайде максимум одна плашка и максимум один эмодзи.

ПРОДУКТ В КАДРЕ
- Packshot — на отдельном слайде, на однотонном фоне, мягкая тень снизу.
- Этикетку НИЧЕМ не перекрывать: ни текстом, ни плашкой, ни эмодзи.
- Логотип — круглый navy-значок BP, только в финальном слайде, размер ≤ 120 px.

РОЛИ СЛАЙДОВ (композиция каждого должна отличаться от соседнего)
1. Хук — крупная типографика на плашке, фото фоном.
2. Проблема/узнавание — фото крупным планом, текст в нижней трети.
3. Объяснение — схема, список из 3 пунктов или сравнение до/после.
4. Продукт — packshot по центру, текст сверху.
5. Финал/CTA — минимум текста, логотип, одна строка действия.
Подряд два слайда с одинаковой компоновкой — брак. Карусель из 5 одинаковых
«фото + плашка снизу» тоже брак.
"""


_SLIDE_RE = re.compile(r"^\s*[-*]?\s*\**Слайд\s*(\d+)", re.I | re.M)
_REQUIRED = (("layout", "Layout:"), ("текст", "Текст"), ("плашка", "Плашка:"), ("акцент", "Акцент:"))


def validate_layout(text: str) -> list[str]:
    """Проверка ТЗ на графику: у каждого слайда есть роль, компоновка, плашка и акцент.

    Ловит ровно то, на что ругалась Вика: слайды-близнецы и плашки без заданной позиции.
    """
    problems: list[str] = []
    lines = [l.strip() for l in (text or "").split("\n") if _SLIDE_RE.match(l)]
    if not lines:
        return problems                       # это не карусель — проверять нечего

    layouts: list[str] = []
    for l in lines:
        num = _SLIDE_RE.match(l).group(1)
        for human, token in _REQUIRED:
            if token.lower() not in l.lower():
                problems.append(f"слайд {num}: не указан блок «{human}»")
        m = re.search(r"Layout:\s*([^·|]+)", l, re.I)
        layouts.append(re.sub(r"\W+", " ", (m.group(1) if m else "")).strip().lower())

    for i in range(1, len(layouts)):
        if layouts[i] and layouts[i] == layouts[i - 1]:
            problems.append(f"слайды {i} и {i+1} с одинаковой компоновкой — подряд так нельзя")
    if len(layouts) > 2 and len(set(x for x in layouts if x)) == 1:
        problems.append("вся карусель на одной компоновке — нужны разные роли слайдов")
    return problems
